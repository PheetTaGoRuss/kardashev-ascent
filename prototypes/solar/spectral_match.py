"""Detailed-balance (Shockley-Queisser) efficiency of single-junction cells under blackbody stars.

    python prototypes/solar/spectral_match.py

Prints the table and regenerates Assets/_Project/Scripts/Simulation/Solar/SpectralMatchTable.cs.
f_spec = eta(star) / eta(5778 K blackbody): the factor PanelParams.FSpec expects.

Model (docs/physics/notes/stellar_exoplanet.md, section 1): blackbody star scaled to 1000 W/m^2,
step absorptance above E_g, radiative recombination only, cell at 300 K, emission from one face.
"""
from __future__ import annotations

import math
from pathlib import Path

import numpy as np

H = 6.62607015e-34       # J s
C = 2.99792458e8         # m/s
K_B = 1.380649e-23       # J/K
Q = 1.602176634e-19      # C
SIGMA = 5.670374419e-8   # W m^-2 K^-4
T_CELL = 300.0
INCIDENT = 1000.0        # W/m^2
SUN_REF = 5778.0

MATERIALS = {            # bandgap at 300 K, eV
    "Silicon": 1.12,
    "GaAs": 1.42,
    "CdTe": 1.50,
    "Germanium": 0.67,
    "Perovskite": 1.55,  # MAPbI3-class; tunable ~1.2-2.3 eV
}
TEMPERATURES = list(range(2300, 7600, 100))

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "Assets" / "_Project" / "Scripts" / "Simulation" / "Solar" / "SpectralMatchTable.cs"


def photon_flux_above(eg_ev: float, temp: float) -> float:
    """Hemispherical blackbody photon flux with E > E_g, photons m^-2 s^-1."""
    kt = K_B * temp
    x0 = eg_ev * Q / kt
    x = np.linspace(x0, x0 + 60.0, 200_001)
    integrand = x * x / np.expm1(x)
    integral = float(np.sum((integrand[1:] + integrand[:-1]) * 0.5 * (x[1] - x[0])))
    return 2.0 * math.pi * kt ** 3 / (H ** 3 * C ** 2) * integral


def efficiency(eg_ev: float, star_temp: float) -> float:
    jsc = Q * photon_flux_above(eg_ev, star_temp) * INCIDENT / (SIGMA * star_temp ** 4)
    j0 = Q * photon_flux_above(eg_ev, T_CELL)
    vt = K_B * T_CELL / Q
    voc = vt * math.log(jsc / j0 + 1.0)
    v = np.linspace(0.0, voc, 20_001)
    power = v * (jsc - j0 * np.expm1(v / vt))
    return float(power.max()) / INCIDENT


def main() -> None:
    eta = {m: [efficiency(eg, t) for t in TEMPERATURES] for m, eg in MATERIALS.items()}
    ref = {m: efficiency(eg, SUN_REF) for m, eg in MATERIALS.items()}

    print("T_eff  " + "  ".join(f"{m:>10}" for m in MATERIALS))
    for i, t in enumerate(TEMPERATURES):
        if t in (2600, 3000, 3500, 4500, 5800, 6500):
            print(f"{t:5d}  " + "  ".join(f"{eta[m][i] / ref[m]:10.3f}" for m in MATERIALS))
    print("eta at 5778 K: " + ", ".join(f"{m} {ref[m]:.4f}" for m in MATERIALS))

    rows = []
    for m in MATERIALS:
        values = ", ".join(f"{e:.5f}" for e in eta[m])
        rows.append(f"            /* {m} */ new[] {{ {values} }},")
    refs = ", ".join(f"{ref[m]:.5f}" for m in MATERIALS)
    code = f"""// <auto-generated> by prototypes/solar/spectral_match.py. Do not edit by hand. </auto-generated>
namespace KardashevAscent.Simulation.Solar
{{
    static class SpectralMatchTable
    {{
        public const double FirstTemperatureK = {TEMPERATURES[0]:.1f};
        public const double StepK = {TEMPERATURES[1] - TEMPERATURES[0]:.1f};

        /// <summary>Detailed-balance efficiency per <see cref="CellMaterial"/> (row) and star temperature (column).</summary>
        public static readonly double[][] Efficiency =
        {{
{chr(10).join(rows)}
        }};

        /// <summary>Efficiency under a 5778 K blackbody per material, the f_spec reference.</summary>
        public static readonly double[] SunReference = {{ {refs} }};
    }}
}}
"""
    OUT.write_text(code, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()

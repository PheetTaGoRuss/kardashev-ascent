"""Earth's monthly ground reflectance and aerosol haze by latitude from NASA POWER, baked into C# for Earth-like planets.

    python tools/nasa_power/fetch_ground_and_haze.py            # fetch (136 requests) and generate
    python tools/nasa_power/fetch_ground_and_haze.py --offline  # regenerate C# from the cache

ALLSKY_SRF_ALB = all-sky surface albedo (share of sunlight the ground reflects); AOD_55 = aerosol optical depth at
550 nm (MERRA-2). Each latitude row is the mean over 8 longitudes (every 45 deg), the same grid as the clouds and
the air temperature. Standard library only.
"""
from __future__ import annotations

import argparse
import json
import sys
import time
import urllib.parse
import urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
CACHE = HERE / "cache" / "ground_haze_points.json"
OUT = ROOT / "Assets" / "_Project" / "Scripts" / "Simulation" / "Climate" / "GroundAndHazeTable.cs"
API = "https://power.larc.nasa.gov/api/temporal/climatology/point"
LATITUDES = list(range(-80, 81, 10))
LONGITUDES = list(range(-180, 180, 45))
MONTHS = ["JAN", "FEB", "MAR", "APR", "MAY", "JUN", "JUL", "AUG", "SEP", "OCT", "NOV", "DEC"]


def fetch_point(lat: int, lon: int) -> dict:
    query = urllib.parse.urlencode({
        "parameters": "ALLSKY_SRF_ALB,AOD_55", "community": "RE", "latitude": lat, "longitude": lon, "format": "JSON"})
    request = urllib.request.Request(f"{API}?{query}", headers={"User-Agent": "kardashev-ascent-data-tool"})
    for attempt in range(4):
        try:
            with urllib.request.urlopen(request, timeout=90) as response:
                data = json.loads(response.read().decode("utf-8"))
            p = data["properties"]["parameter"]
            return {"albedo": [p["ALLSKY_SRF_ALB"][m] for m in MONTHS],
                    "aod": [p["AOD_55"][m] for m in MONTHS],
                    "range": data["header"].get("range", "")}
        except (OSError, ValueError, KeyError) as error:
            if attempt == 3:
                raise
            print(f"  retry {lat},{lon}: {error}", file=sys.stderr)
            time.sleep(2 ** (attempt + 1))
    raise RuntimeError("unreachable")


def zonal(points: dict, key: str, fallback: float) -> list[list[float]]:
    rows = []
    for lat in LATITUDES:
        row = []
        for m in range(12):
            valid = [v for v in (points[f"{lat},{lon}"][key][m] for lon in LONGITUDES) if v >= 0]   # -999 = missing
            row.append(sum(valid) / len(valid) if valid else fallback)
        rows.append(row)
    # A month with no value anywhere on a row (polar night: no albedo) takes the row's mean of the other months.
    for r, row in enumerate(rows):
        have = [v for v, m in zip(row, range(12)) if any(points[f"{LATITUDES[r]},{lon}"][key][m] >= 0 for lon in LONGITUDES)]
        mean = sum(have) / len(have) if have else fallback
        rows[r] = [v if any(points[f"{LATITUDES[r]},{lon}"][key][m] >= 0 for lon in LONGITUDES) else mean for m, v in enumerate(row)]
    return rows


def table(name: str, rows: list[list[float]], fmt: str) -> str:
    body = "\n".join(f"            /* {lat:+3d} */ new[] {{ {', '.join(format(v, fmt) for v in row)} }},"
                     for lat, row in zip(LATITUDES, rows))
    return f"""        public static readonly double[][] {name} =
        {{
{body}
        }};"""


def write_csharp(albedo, aod, data_range: str, retrieved: str) -> None:
    OUT.write_text(f"""// <auto-generated> by tools/nasa_power/fetch_ground_and_haze.py. Do not edit by hand. </auto-generated>
namespace KardashevAscent.Simulation.Climate
{{
    /// <summary>
    /// NASA POWER climatology ({data_range}), retrieved {retrieved}, mean of 8 longitudes per latitude.
    /// Rows: latitude {LATITUDES[0]}..{LATITUDES[-1]} deg every {LATITUDES[1] - LATITUDES[0]} deg. Columns: January..December.
    /// Albedo: ALLSKY_SRF_ALB (all-sky surface albedo; polar-night months take the row's mean).
    /// Aod550: AOD_55 (aerosol optical depth at 550 nm, MERRA-2).
    /// </summary>
    static class GroundAndHazeTable
    {{
        public const double FirstLatitudeDeg = {LATITUDES[0]:.1f};
        public const double StepDeg = {LATITUDES[1] - LATITUDES[0]:.1f};

{table("Albedo", albedo, ".3f")}

{table("Aod550", aod, ".3f")}
    }}
}}
""", encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--offline", action="store_true")
    args = parser.parse_args()
    if args.offline:
        cache = json.loads(CACHE.read_text(encoding="utf-8"))
    else:
        points = {}
        for lat in LATITUDES:
            for lon in LONGITUDES:
                points[f"{lat},{lon}"] = fetch_point(lat, lon)
            print(f"lat {lat:+d} done", flush=True)
        cache = {"retrieved": time.strftime("%Y-%m-%d"), "points": points}
        CACHE.parent.mkdir(parents=True, exist_ok=True)
        CACHE.write_text(json.dumps(cache, indent=1) + "\n", encoding="utf-8")
    points = cache["points"]
    albedo = zonal(points, "albedo", 0.15)
    aod = zonal(points, "aod", 0.1)
    write_csharp(albedo, aod, next(iter(points.values()))["range"], cache["retrieved"])
    for lat, a, t in zip(LATITUDES, albedo, aod):
        print(f"{lat:+3d}  albedo " + " ".join(f"{v:.2f}" for v in a) + "  | aod " + " ".join(f"{v:.2f}" for v in t))
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

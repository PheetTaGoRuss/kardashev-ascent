"""Earth's relative humidity at 2 m by latitude and month from NASA POWER daily data (RH2M, MERRA-2, 2001-2025), baked into C#.

    python tools/nasa_power/fetch_humidity.py            # fetch (68 requests) and generate
    python tools/nasa_power/fetch_humidity.py --offline  # regenerate C# from the cache

For each 10-degree latitude row and month: the mean RH (percent) and the standard deviation of the daily anomaly (the day minus the multi-year mean of its
day of the year, smoothed over 15 days). 4 longitudes per row, like the other daily tool. Standard library only.
"""
from __future__ import annotations

import argparse
import json
import math
import sys
import time
import urllib.parse
import urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
CACHE = HERE / "cache" / "humidity_points.json"
OUT = ROOT / "Assets" / "_Project" / "Scripts" / "Simulation" / "Climate" / "HumidityTable.cs"
API = "https://power.larc.nasa.gov/api/temporal/daily/point"
LATITUDES = list(range(-80, 81, 10))
LONGITUDES = [-180, -90, 0, 90]
START, END = "20010101", "20251231"


def fetch_point(lat: int, lon: int) -> dict:
    query = urllib.parse.urlencode({"parameters": "RH2M", "community": "RE", "latitude": lat, "longitude": lon, "start": START, "end": END, "format": "JSON"})
    request = urllib.request.Request(f"{API}?{query}", headers={"User-Agent": "kardashev-ascent-data-tool"})
    for attempt in range(4):
        try:
            with urllib.request.urlopen(request, timeout=120) as response:
                data = json.loads(response.read().decode("utf-8"))
            return data["properties"]["parameter"]["RH2M"]
        except (OSError, ValueError, KeyError) as error:
            if attempt == 3:
                raise
            print(f"  retry {lat},{lon}: {error}", file=sys.stderr)
            time.sleep(2 ** (attempt + 1))
    raise RuntimeError("unreachable")


def day_of_year(date: str) -> int:
    y, m, d = int(date[:4]), int(date[4:6]), int(date[6:])
    cum = [0, 31, 59, 90, 120, 151, 181, 212, 243, 273, 304, 334]
    leap = 1 if (y % 4 == 0 and (y % 100 != 0 or y % 400 == 0)) and m > 2 else 0
    return cum[m - 1] + d + leap


def month_stats(series: dict) -> tuple[list[float], list[float]]:
    values = [(d, v) for d, v in sorted(series.items()) if v > -900]
    sums, counts = [0.0] * 366, [0] * 366
    for d, v in values:
        sums[day_of_year(d) - 1] += v
        counts[day_of_year(d) - 1] += 1
    clim = [sums[i] / counts[i] if counts[i] else float("nan") for i in range(366)]
    smooth = []
    for i in range(366):
        w = [clim[(i + k) % 366] for k in range(-7, 8) if not math.isnan(clim[(i + k) % 366])]
        smooth.append(sum(w) / len(w) if w else float("nan"))
    mean, sd = [], []
    for m in range(12):
        vs = [v for d, v in values if int(d[4:6]) - 1 == m]
        an = [v - smooth[day_of_year(d) - 1] for d, v in values if int(d[4:6]) - 1 == m]
        mean.append(sum(vs) / len(vs))
        mu = sum(an) / len(an)
        sd.append(math.sqrt(sum((a - mu) ** 2 for a in an) / len(an)))
    return mean, sd


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--offline", action="store_true")
    args = ap.parse_args()
    CACHE.parent.mkdir(parents=True, exist_ok=True)
    points = json.loads(CACHE.read_text(encoding="utf-8")) if CACHE.exists() else {}
    if not args.offline:
        for lat in LATITUDES:
            for lon in LONGITUDES:
                key = f"{lat},{lon}"
                if key in points:
                    continue
                print("fetch", key, file=sys.stderr)
                points[key] = fetch_point(lat, lon)
                CACHE.write_text(json.dumps(points), encoding="utf-8")
    mean_rows, sd_rows = [], []
    for lat in LATITUDES:
        ms, ss = zip(*(month_stats(points[f"{lat},{lon}"]) for lon in LONGITUDES))
        mean_rows.append([sum(c) / len(c) for c in zip(*ms)])
        sd_rows.append([sum(c) / len(c) for c in zip(*ss)])

    def block(name: str, doc: str, rows: list[list[float]]) -> str:
        body = "\n".join(f"            /* {lat:+3d} */ new[] {{ {', '.join(format(v, '.1f') for v in row)} }}," for lat, row in zip(LATITUDES, rows))
        return f"        /// <summary>{doc}</summary>\n        public static readonly double[][] {name} =\n        {{\n{body}\n        }};\n"
    OUT.write_text(f"""// <auto-generated> by tools/nasa_power/fetch_humidity.py. Do not edit by hand. </auto-generated>
namespace KardashevAscent.Simulation.Climate
{{
    /// <summary>
    /// NASA POWER daily RH2M ({START[:4]}-{END[:4]}, MERRA-2), retrieved {time.strftime("%Y-%m-%d")}: relative humidity at 2 m, percent, by latitude and month, pooled over 4 longitudes.
    /// Rows: latitude {LATITUDES[0]}..{LATITUDES[-1]} deg every {LATITUDES[1] - LATITUDES[0]} deg. Columns: January..December.
    /// </summary>
    static class HumidityTable
    {{
{block("Mean", "Mean relative humidity at 2 m, percent.", mean_rows)}
{block("Sd", "Standard deviation of the daily anomaly of the relative humidity, percentage points.", sd_rows)}    }}
}}
""", encoding="utf-8")
    print("wrote", OUT)


if __name__ == "__main__":
    main()

"""Earth's monthly air temperature by latitude from NASA POWER, baked into C# for Earth-like planets.

    python tools/nasa_power/fetch_air_temperature.py            # fetch (136 requests) and generate
    python tools/nasa_power/fetch_air_temperature.py --offline  # regenerate C# from the cache

T2M = air temperature 2 m above the ground (deg C), NASA POWER monthly climatology (MERRA-2). Each latitude row is
the mean over 8 longitudes (every 45 deg), so it mixes land and ocean like Earth does; the same grid as
fetch_cloud_factor.py. Standard library only.
"""
from __future__ import annotations

import argparse
import json
import sys
import time
import urllib.parse
import urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
CACHE = HERE / "cache" / "air_temperature_points.json"
OUT = ROOT / "Assets" / "_Project" / "Scripts" / "Simulation" / "Climate" / "AirTemperatureTable.cs"
API = "https://power.larc.nasa.gov/api/temporal/climatology/point"
LATITUDES = list(range(-80, 81, 10))
LONGITUDES = list(range(-180, 180, 45))
MONTHS = ["JAN", "FEB", "MAR", "APR", "MAY", "JUN", "JUL", "AUG", "SEP", "OCT", "NOV", "DEC"]


def fetch_point(lat: int, lon: int) -> dict:
    query = urllib.parse.urlencode({
        "parameters": "T2M", "community": "RE", "latitude": lat, "longitude": lon, "format": "JSON"})
    request = urllib.request.Request(f"{API}?{query}", headers={"User-Agent": "kardashev-ascent-data-tool"})
    for attempt in range(4):
        try:
            with urllib.request.urlopen(request, timeout=90) as response:
                data = json.loads(response.read().decode("utf-8"))
            units = data["parameters"]["T2M"]["units"]
            if units != "C":
                raise ValueError(f"unexpected units {units}")
            p = data["properties"]["parameter"]["T2M"]
            return {"t2m": [p[m] for m in MONTHS], "range": data["header"].get("range", "")}
        except (OSError, ValueError) as error:
            if attempt == 3:
                raise
            print(f"  retry {lat},{lon}: {error}", file=sys.stderr)
            time.sleep(2 ** (attempt + 1))
    raise RuntimeError("unreachable")


def zonal_means(points: dict) -> list[list[float]]:
    rows = []
    for lat in LATITUDES:
        row = []
        for m in range(12):
            values = [points[f"{lat},{lon}"]["t2m"][m] for lon in LONGITUDES]
            valid = [v for v in values if v > -900]   # -999 = missing
            row.append(sum(valid) / len(valid))
        rows.append(row)
    return rows


def write_csharp(rows: list[list[float]], data_range: str, retrieved: str) -> None:
    body = "\n".join(
        f"            /* {lat:+3d} */ new[] {{ {', '.join(f'{v:.1f}' for v in row)} }},"
        for lat, row in zip(LATITUDES, rows))
    OUT.write_text(f"""// <auto-generated> by tools/nasa_power/fetch_air_temperature.py. Do not edit by hand. </auto-generated>
namespace KardashevAscent.Simulation.Climate
{{
    /// <summary>
    /// NASA POWER climatology ({data_range}), retrieved {retrieved}: T2M, air temperature 2 m above the ground, deg C,
    /// mean of 8 longitudes per latitude. Rows: latitude {LATITUDES[0]}..{LATITUDES[-1]} deg every
    /// {LATITUDES[1] - LATITUDES[0]} deg. Columns: January..December.
    /// </summary>
    static class AirTemperatureTable
    {{
        public const double FirstLatitudeDeg = {LATITUDES[0]:.1f};
        public const double StepDeg = {LATITUDES[1] - LATITUDES[0]:.1f};

        public static readonly double[][] Celsius =
        {{
{body}
        }};
    }}
}}
""", encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--offline", action="store_true")
    args = parser.parse_args()

    if args.offline:
        cache = json.loads(CACHE.read_text(encoding="utf-8"))
    else:
        points = {}
        for lat in LATITUDES:
            for lon in LONGITUDES:
                points[f"{lat},{lon}"] = fetch_point(lat, lon)
            print(f"lat {lat:+d} done", flush=True)
        cache = {"retrieved": time.strftime("%Y-%m-%d"), "points": points}
        CACHE.parent.mkdir(parents=True, exist_ok=True)
        CACHE.write_text(json.dumps(cache, indent=1) + "\n", encoding="utf-8")

    points = cache["points"]
    rows = zonal_means(points)
    data_range = next(iter(points.values()))["range"]
    write_csharp(rows, data_range, cache["retrieved"])
    for lat, row in zip(LATITUDES, rows):
        print(f"{lat:+3d}  " + " ".join(f"{v:5.1f}" for v in row) + f"  | year {sum(row) / 12:5.1f}")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
